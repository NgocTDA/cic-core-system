export const generateRunLogs = (jobId: string, status: 'SUCCESS' | 'FAILED'): NonNullable<IJobRun['logs']> => {
  const logs: NonNullable<IJobRun['logs']> = [
    { timestamp: new Date(Date.now() - 60000).toISOString(), level: 'INFO' as const, step: 'Initialization', message: `[${jobId}] Job started, initializing...` },
    { timestamp: new Date(Date.now() - 50000).toISOString(), level: 'INFO' as const, step: 'Connection', message: 'Connecting to data source...' },
    { timestamp: new Date(Date.now() - 40000).toISOString(), level: 'INFO' as const, step: 'Validation', message: 'Validating data schema...' },
    { timestamp: new Date(Date.now() - 30000).toISOString(), level: 'INFO' as const, step: 'Processing', message: 'Processing 5000 records...' },
  ];

  if (status === 'FAILED') {
    logs.push({ timestamp: new Date(Date.now() - 20000).toISOString(), level: 'WARN' as const, step: 'Processing', message: 'Warning: 10 records skipped due to validation error' });
    logs.push({ timestamp: new Date(Date.now() - 10000).toISOString(), level: 'ERROR' as const, step: 'Processing', message: 'Error: Database connection timeout after 30s' });
  } else {
    logs.push({ timestamp: new Date(Date.now() - 20000).toISOString(), level: 'INFO' as const, step: 'Completion', message: 'All 5000 records processed successfully' });
    logs.push({ timestamp: new Date(Date.now() - 10000).toISOString(), level: 'INFO' as const, step: 'Cleanup', message: 'Closing database connections...' });
    logs.push({ timestamp: new Date(Date.now() - 5000).toISOString(), level: 'INFO' as const, step: 'Summary', message: 'Job completed successfully. Duration: 1m 55s' });
  }

  return logs;
};

